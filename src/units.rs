//! Unit labels from the Go format-research catalog. These are compiled identifiers,
//! not templates or runtime assets. Labels do not imply conversion of source values.
use crate::PropertyNode;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
pub enum PropertyUnit {
    Pixels,
    Degrees,
    Percent,
    Seconds,
    Decibels,
}
impl PropertyUnit {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Pixels => "pixels",
            Self::Degrees => "degrees",
            Self::Percent => "percent",
            Self::Seconds => "seconds",
            Self::Decibels => "dB",
        }
    }
}

/// Catalog lookup only. Unknown match names return None.
pub fn property_unit(match_name: &str) -> Option<PropertyUnit> {
    let i = UNITS
        .binary_search_by_key(&match_name, |(name, _)| *name)
        .ok()?;
    UNITS.get(i).map(|(_, unit)| *unit)
}
/// Iterate all compiled entries in lexical match-name order without allocating.
pub fn known_property_units() -> impl ExactSizeIterator<Item = (&'static str, PropertyUnit)> {
    UNITS.iter().copied()
}
impl PropertyNode {
    /// Known unit label, falling back to degrees for a file-declared angle control.
    pub fn units(&self) -> Option<PropertyUnit> {
        property_unit(&self.match_name).or_else(|| {
            (self.property.as_ref()?.metadata.control_type == Some(3))
                .then_some(PropertyUnit::Degrees)
        })
    }
}
